#' @name mlm_data
#'
#' @title Data Objects for Multiple Linear Regression Models
#'
#' @description Methods for preparing and working with data sets for
#'   fitting multiple linear regression (MLM) models. MLM data sets
#'   are implemented in a modular (\dQuote{object-oriented})
#'   interface, which allows for different types of MLM data (see
#'   \sQuote{Details} for a general specification of MLM data
#'   classes).
#'
#' @param X An n x J matrix containing observations about J candidate
#'   explanatory variables.
#'
#' @param y A vector of regression outcomes.
#'
#' @param standardize If \code{standardize = TRUE}, columns of X are
#'   standardized. If variables are in the same units already, you
#'   might not wish to standardize. Coefficients are always returned
#'   on the original scale.
#'
#' @return An \sQuote{mlm_data} object. It is a list with the
#'   following elements (and possbly others):
#'
#'   \item{n}{The number of samples.}
#'
#'   \item{nvar}{The number of variables.}
#'
#'   \item{var_y}{This is \code{var_y = sum(y^2)/(n-1)}.
#'     It will be equal to \code{var(y)} if y is centered
#'     (i.e., has a mean of zero).}
#'
#'   \item{ss}{An \sQuote{ser_data} object giving summary statistics
#'     derived from the MLM data (summary statistics are obtained
#'     under the assumption that the residual variance is 1). See
#'     \code{\link{prepare_ser_data}} for details.}
#'
#'   \item{xs}{Scaling factors applied to the variables (e.g., columns
#'     of X). If no scaling is applied, this should be a vector of
#'     ones.}
#'
#' @details \bold{Design of MLM data classes.}
#' 
#'   An MLM data object defines a data set for J candidate explanatory
#'   variables measured in n samples and a response variable or
#'   regression outcome. The canonical representation of MLM data is
#'   an n x J matrix X (containing measurements of the candidate
#'   explanatory ariables and a vector y of length n (containing
#'   measurements of the response variable). This canonical
#'   representation is generated by \code{prepare_mlm_full_data}.
#'   Other representations of MLM data are defined as MLM data
#'   classes.
#' 
#'   An \dQuote{MLM data} class has at a minimum the following elements:
#'   \enumerate{
#'
#'   \item A function that creates the MLM data object (e.g.,
#'     \code{prepare_mlm_full_data}). It should return an object of
#'     class \sQuote{mlm_data}.
#'
#'   \item A \sQuote{sample.names} method that returns the sample
#'     names.
#'
#'   \item A \sQuote{variable.names} method that returns the variable
#'     names.
#'
#'   \item Print and summary methods that output a summary of the
#'     data.
#'
#'   \item A compute_XtXb method that returns the matrix-vector
#'     product \code{drop(crossprod(X) \%*\% b)} for a vector
#'     \code{b} of length J.
#'   }
#'
#' @export
#'
prepare_mlm_full_data <- function (X, y, standardize = FALSE) {
  # 
  # TO DO:  
  #
  # - Define "mlm_data" class in the documentation.
  # - Implement intercept = TRUE.
  # - Add intercept estimate to data object.
  #

  # Check and process the inputs.  
  if (!(is.numeric(y) & 
        length(y) > 1))
    stop("y should be a numeric vector containing at least 2 data points",
         domain = NA)
  if (!(is.numeric(X) &
        is.matrix(X) &
        nrow(X) == length(y) &
        nrow(X) > 1 &
        ncol(X) > 1))
    stop("X should be a numeric matrix with at least 2 rows and 2 ",
         "columns, and nrow(X) should be the same as length(y)",
         domain = NA)
    
  # Check the variable and sample names.
  if (is.null(names(y)) | 
      is.null(rownames(X)) |
      is.null(colnames(X)))
    stop("Elements of y, and rows and columns of X, need to be named",
         domain = NA)
  if (any(names(y) != rownames(X)))
    stop("Sample names in X and y are not consistent",domain = NA)
    
  # For now, automatically center X and y. 
  # (TO DO: make this an option).
  # 
  # Standardize the columns of X, if requested.
  if (standardize) {
    X <- scale(X,center = TRUE,scale = TRUE)
    xs <- attr(X,"scaled:scale")
  } else {
    X <- scale(X,center = TRUE,scale = FALSE)
    xs <- rep(1,J)
  }
  names(xs) <- colnames(X)

  # Prepare the output.
  n <- nrow(X)
  J <- ncol(X)
  dat <- list(n     = n,
              nvar  = J,
              X     = X,
              y     = y,
              var_y = sum(y^2)/(n-1),
              ss    = prepare_ser_data(X = X,y = y,residual_variance = 1),
              xs    = xs,
              standardize = standardize)
  class(dat) <- c("mlm_full_data","mlm_data","list")
  return(dat)
}

#' @rdname mlm_data
#' 
#' @param z A vector of z-scores (not yet implemented).
#'
#' @param R A J x J correlation matrix.
#'
#' @param bhat A vector of length J containing least-squares estimates
#'   of the coefficients (e.g., estimated using \code{\link[stats]{lm}}).
#'
#' @param sehat A vector of length J containing the standard errors
#'   of the least-squares estimates.
#' 
#' @param n The number of samples.
#'
#' @param var_y This should be equal to \code{sum(y^2)/(n-1)}.
#'   If y has a mean of zero, this should be the same as
#'   \code{var(y)}.
#'
#' @export
#' 
prepare_mlm_summary_data <- function (z, R, bhat, sehat, n, var_y) {
  #  
  # NOTES: 
  # - Be strict about naming things.
  # - I need to do a better job checking the inputs.
  # - Handle situation when n and/or var_y are missing.
  # - Give messages/warnings to tell user what is going on.
  # - See susie_rss.R.
  # - Assume n is provided, but not necessarily var_y.
  #
  # TO DO:
  # - Check that susie with z-scores produces the same result as
  #   susie with full data when X is standardized. (I don't think 
  #   Y needs to be standardized so long as var_y is provided?)
  #
  if (!missing(z))
    stop("z-scores are not yet implemented")
  
  # Check and process the inputs.  
  if (!(is.numeric(bhat) & 
        length(bhat) > 1 & 
        is.numeric(sehat) & 
        length(bhat) == length(sehat)))
    stop("bhat and sehat should be vectors of the same length")
  if (is.null(names(bhat)) | 
      is.null(names(sehat)))
    stop("bhat and sehat should have named elements")
  if (any(names(bhat) != names(sehat)))
    stop("variable names in bhat and sehat do not match")
  J <- length(bhat)
  if (any(sehat <= 0))
    stop("standard errors sehat should be positive")
  if (n < 2)
    stop("sample size (n) should be 2 or greater")
  if (var_y <= 0)
    stop("var_y should be positive")
  if (!(is.matrix(R) & 
        NROW(R) == J & 
        NCOL(R) == J))
    stop("R should be a J x J symmetric matrix, J = number of variables")
  if (is.null(rownames(R)) | 
      is.null(colnames(R)))
    stop("Row and columns of R should be named")
  if (any(rownames(R) != names(bhat)) |
      any(colnames(R) != names(bhat)))
    stop("row and column names in R do not match bhat, shat")

  # See Lemma 1 of the susie-rss paper (Zou et al 2022 PLoS 
  # Genetics).
  z     <- bhat/sehat
  sigma <- var_y*(n-1)/(z^2 + n - 2)
  d     <- sqrt(sigma)/sehat
  XtX   <- t(R * d) * d
  XtX   <- (XtX + t(XtX))/2
  ss    <- prepare_ser_data(bhat = bhat,shat = 1/d^2,residual_variance = 1)

  # Prepare the output.
  dat <- list(n     = n,
              nvar  = J,
              XtX   = XtX,
              var_y = var_y,
              ss    = ss,
              xs    = setNames(rep(1,J),names(bhat)))
  class(dat) <- c("mlm_summary_data","mlm_data","list")
  return(dat)
}

#'
#' @export 
#' 
sample.names.mlm_full_data <- function (dat, ...)
  names(object$y)

#'
#' @importFrom stats variable.names
#' 
#' @export  
#'
variable.names.mlm_full_data <- function (object, ...)
  colnames(object$X)

#'
#' @export
#'
variable.names.mlm_summary_data <- function (object, ...)
  rownames(object$ss)

#' 
#' @export
#' 
summary.mlm_full_data <- function (object, ...) {
  out <- list(n = object$n,
              nvar = object$nvar,
              standardize = object$standardize)
  class(out) <- c("summary_mlm_full_data","list")
  return(out)
}

#'
#' @export
#' 
summary.mlm_summary_data <- function (object, ...) {
  out <- list(n = object$n,nvar = object$nvar)
  class(out) <- c("summary_mlm_summary_data","list")
  return(out)
}

#'
#' @export
#' 
print.summary_mlm_full_data <- function (x, ...) {
  cat(sprintf("Individual-level data for %d variables in %d samples.\n",
              x$n,x$nvar))
  cat(sprintf("Variables %s standardized.\n",
              ifelse(x$standardize,"are","are not")))
  return(invisible(x))
}

#'
#' @export
#' 
print.summary_mlm_summary_data <- function (x, ...) {
  cat(sprintf("Summary data for %d variables.\n",x$nvar))
  cat(sprintf("The sample size is %d.\n",x$n))
  return(invisible(x))
}

